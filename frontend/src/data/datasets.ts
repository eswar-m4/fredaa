import { VERTICAL_DATASETS } from "./vertical-datasets";

// Universal dataset schemas for "By Dataset" use case.
// Each dataset = a standard schema + the system sources we have wired
// + the workflow that runs behind the scenes + a refresh cadence.
// Attribute lists are intentionally comprehensive — users pick a subset.

export type DatasetField = {
  key: string;
  label: string;
  type: "string" | "number" | "boolean" | "date" | "geo" | "url" | "email" | "enum";
  role: "input" | "output";
  required?: boolean;
  example?: string;
  group?: string; // section grouping in the field-mapping UI
};

export type DatasetSource = {
  name: string;
  url: string;
  region?: string;
  attributes: number; // attrs this source contributes
};

export type Dataset = {
  id: string;
  name: string;
  category:
    | "Company"
    | "People"
    | "Education"
    | "Commerce"
    | "Location"
    | "Automotive"
    | "Healthcare"
    | "Hospitality"
    | "Legal"
    | "Insurance"
    | "Real Estate"
    | "Travel"
    | "Jobs"
    | "Financial"
    | "News & Media"
    | "Competitive";
  tagline: string;
  description: string;
  icon: string;
  refreshDefault: "Real-time" | "Hourly" | "Daily" | "Weekly" | "Monthly" | "Quarterly";
  refreshOptions: string[];
  rowsAvailable: string;
  /** Coverage % across the universe — e.g. 92 means 92% of records have most attributes filled. */
  coverage?: number;
  /** AI extraction accuracy %, measured against a labeled golden set. */
  accuracy?: number;
  /** Number of countries / locales covered by wired sources. */
  countriesCovered?: number;
  inputAttributes: DatasetField[];
  inputTemplateColumns?: DatasetField[];
  outputAttributes: DatasetField[];
  sources: DatasetSource[]; // system sources wired for this dataset
  workflowId: string; // single embedded workflow (hidden from user)
  sampleRow: Record<string, string | number | boolean>;
};

